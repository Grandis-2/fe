import { OPTION_PRESETS, type ProductOptionPreset } from './optionPreset'

/**
 * 제품 종류별 유의어.
 *
 * 검색은 태그에 적힌 글자를 그대로 본다 — '핸드폰'으로 찾는 손님에게 걸리려면
 * 상품이 '핸드폰'이라는 태그를 들고 있어야 한다. 그래서 같은 물건을 가리키는 말을
 * 후보로 같이 깔아 두고, 등록할 때 한 종류의 말들을 함께 고르게 한다.
 *
 * 긴 말 안에 들어 있는 짧은 말('스마트워치'의 '워치')도 따로 둔다 — 서버 검색이
 * 부분 일치인지 단어 일치인지 확정되지 않았고, 단어 일치면 짧은 말은 안 걸린다.
 *
 * 키는 OPTION_PRESETS의 종류 이름이다. 종류가 늘면 여기도 한 줄 붙이고,
 * 없으면 그 종류는 이름만 후보로 나온다.
 */
const SYNONYMS: Record<string, string[]> = {
  스마트폰: ['핸드폰', '휴대폰'],
  태블릿: ['패드', '타블렛'],
  폴더블: ['폴드', '플립', '접는폰'],
  노트북: ['랩탑', '랩톱'],
  데스크탑: ['데스크톱', 'PC', '본체'],
  모니터: ['디스플레이', '화면'],
  스마트워치: ['워치', '시계'],
  무선이어폰: ['이어폰', '이어버드'],
  스마트밴드: ['밴드'],
}

/**
 * 대분류별로 자주 붙는 말. 종류가 달라도 같은 묶음이면 비슷하게 찾는다 —
 * PC/주변기기는 쓰임새(게이밍·사무용)로, 웨어러블은 선물로 많이 검색된다.
 */
const CATEGORY_TAGS: Record<string, string[]> = {
  모바일: ['신제품', '한정판'],
  'PC/주변기기': ['게이밍', '사무용', '고사양'],
  웨어러블: ['선물', '신제품'],
}

/**
 * 종류와 무관하게 아무 상품에나 붙을 수 있는 말. 추천에는 묶음에 맞는 것만 올라가고
 * 나머지는 전체 목록에서 고른다.
 */
const GENERAL_TAGS = [
  '신제품',
  '한정판',
  '고사양',
  '가성비',
  '게이밍',
  '사무용',
  '선물',
]

/**
 * 고른 제품 종류에 맞는 추천 태그 — 그 종류의 말(유의어 포함) 다음에 대분류 공통 말.
 *
 * 종류를 아직 고르지 않았으면(수정 폼 포함) 빈 배열이다. 추천이 없다고 태그를 못 다는
 * 건 아니라, 그때는 전체 목록을 펼쳐 고르거나 직접 적는다.
 */
export function recommendedTags(preset?: ProductOptionPreset): string[] {
  if (!preset) return []

  return [
    preset.name,
    ...(SYNONYMS[preset.name] ?? []),
    ...(CATEGORY_TAGS[preset.category] ?? []),
  ]
}

/**
 * 검색 태그 후보 전체. 구매자 화면에는 나오지 않고 검색어로만 쓰인다.
 *
 * 제품 종류는 OPTION_PRESETS에서 가져온다 — 등록 폼이 이미 같은 목록으로 옵션을
 * 깔고 있어서, 목록을 두 벌 두면 종류가 늘어날 때 한쪽만 늘어난다. 종류와 그
 * 유의어를 나란히 세워서 한 묶음을 같이 고르기 쉽게 한다.
 *
 * 여기서 걸러내지 않는다 — 추천(recommendedTags)은 위에 따로 깔리고, 이 목록은
 * 추천에 없는 말을 찾아 고르는 자리다. 종류를 가로질러 쓰는 말도 그래서 다 들어 있다.
 *
 * 후보일 뿐이라 여기 없는 말은 직접 적어 넣는다(TagField).
 */
export const TAG_PRESETS = [
  ...OPTION_PRESETS.flatMap((preset) => [
    preset.name,
    ...(SYNONYMS[preset.name] ?? []),
  ]),
  ...GENERAL_TAGS,
]
